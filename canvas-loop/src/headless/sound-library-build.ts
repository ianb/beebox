// Builds `src/core/sound/library/bundled.generated.ts` from the Kenney originals
// in `sounds/kenney/`: `pnpm sounds:build`. Needs ffmpeg on PATH.
//
// Each variant is decoded to mono at LIBRARY_RATE, trimmed of silence at both
// ends, scaled so its peak is PEAK, and stored as 8-bit G.711 μ-law in base64.
// Decoding happens here, once, so the headless renderer and every browser
// play the same samples.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { LIBRARY_RATE, SAMPLES } from "../core/sound/library/catalog.js";
import { encodeMuLaw } from "../core/sound/library/mulaw.js";

const ROOT = path.resolve(import.meta.dirname, "../..");
const SOURCES = path.join(ROOT, "sounds/kenney");
const OUT = path.join(ROOT, "src/core/sound/library/bundled.generated.ts");

const PEAK = 0.9;
/** Below this fraction of the peak counts as silence when trimming. */
const SILENCE = 0.01;
/** Kept before the first sound and after the last, in seconds. */
const MARGIN = 0.004;

function decode(file: string): Float32Array {
  const raw = execFileSync("ffmpeg", ["-v", "error", "-i", file, "-ac", "1", "-ar", String(LIBRARY_RATE), "-f", "f32le", "-"], {
    maxBuffer: 64 * 1024 * 1024,
  });
  return new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4);
}

function trimAndScale(samples: Float32Array): Float32Array {
  let peak = 0;
  for (const sample of samples) peak = Math.max(peak, Math.abs(sample));
  if (peak === 0) return new Float32Array(0);
  const loud = (sample: number | undefined): boolean => Math.abs(sample ?? 0) >= peak * SILENCE;
  let start = 0;
  while (start < samples.length && !loud(samples[start])) start += 1;
  let end = samples.length;
  while (end > start && !loud(samples[end - 1])) end -= 1;
  const margin = Math.round(MARGIN * LIBRARY_RATE);
  const kept = samples.slice(Math.max(0, start - margin), Math.min(samples.length, end + margin));
  // A short fade at the end, so a trimmed tail does not click.
  const fade = Math.min(kept.length, margin);
  for (let i = 0; i < kept.length; i += 1) {
    const fromEnd = kept.length - 1 - i;
    kept[i] = ((kept[i] ?? 0) / peak) * PEAK * Math.min(1, fromEnd / fade);
  }
  return kept;
}

function main(): void {
  const lines: string[] = [];
  let seconds = 0;
  let bytes = 0;
  for (const [name, entry] of Object.entries(SAMPLES)) {
    const variants = entry.sources.map((source) => {
      const samples = trimAndScale(decode(path.join(SOURCES, source)));
      seconds += samples.length / LIBRARY_RATE;
      bytes += samples.length;
      return Buffer.from(encodeMuLaw(samples)).toString("base64");
    });
    lines.push(`  ${JSON.stringify(name)}: [`, ...variants.map((v) => `    "${v}",`), "  ],");
  }
  const header = [
    "// Generated by `pnpm sounds:build` from canvas-loop/sounds/kenney/ (Kenney, CC0). Do not edit.",
    `// ${Object.keys(SAMPLES).length} names, ${seconds.toFixed(1)} s of audio at ${LIBRARY_RATE} Hz, 8-bit μ-law in base64.`,
    "// Headless code imports this directly; the browser imports it lazily.",
    'import { decodeLibrary } from "./samples.js";',
    'import type { SampleLibrary } from "./samples.js";',
    "",
    "export const SAMPLE_DATA: Readonly<Record<string, readonly string[]>> = {",
  ];
  const footer = [
    "};",
    "",
    "let decoded: SampleLibrary | undefined;",
    "",
    "/** The bundled sample library, decoded on first use. */",
    "export function bundledLibrary(): SampleLibrary {",
    "  decoded ??= decodeLibrary(SAMPLE_DATA);",
    "  return decoded;",
    "}",
    "",
  ];
  writeFileSync(OUT, [...header, ...lines, ...footer].join("\n"));
  process.stdout.write(`wrote ${path.relative(ROOT, OUT)}: ${seconds.toFixed(1)} s, ${(bytes / 1024).toFixed(0)} KB of samples\n`);
}

main();
