/**
 * The `git` shim for walk fixtures (docs/plans/walk-simulated-time.md, Track 5).
 *
 * An agent's shell `git commit` would carry the real date. On a walk fixture
 * `buildEnv` puts `<box>/.beebox/bin` first on PATH; the `git` there sets
 * `GIT_AUTHOR_DATE` and `GIT_COMMITTER_DATE` to the box time and execs the
 * real git. `.beebox/` is gitignored, so the shim is never committed.
 *
 * Box time in the shim: `BBX_TIME` when set (a wait's replay), parsed by the
 * node binary running the server (its absolute path is baked in; `date -d` and
 * `date -j -f` differ between GNU and macOS), else real seconds plus
 * `offsetMs` from `.beebox/clock-offset.json`, read with sed. Dates are set
 * only when the result is a minute or more from real time, matching
 * `boxClockShiftMs`. Variables already set in the environment win.
 */

import * as fs from "node:fs/promises";
import { constants as fsConstants } from "node:fs";
import * as path from "node:path";
import { errnoCode } from "../../shared/error-guards.js";
import { isWalkFixture } from "../../lib/box-fixture.js";
import { clockOffsetPath } from "../../lib/time.js";

export function boxShimDir(boxRoot: string): string {
  return path.join(boxRoot, ".beebox", "bin");
}

function quote(value: string): string {
  return "'" + value.replaceAll("'", "'\\''") + "'";
}

/** The shim script text for a real git at `realGit`. Exported for tests. */
export function gitShimText(input: { realGit: string; nodePath: string; offsetFile: string }): string {
  const { realGit, nodePath, offsetFile } = input;
  return `#!/bin/sh
# Generated by beebox for walk fixtures. Do not edit.
real_git=${quote(realGit)}
if [ -z "$GIT_AUTHOR_DATE$GIT_COMMITTER_DATE" ]; then
  now=$(date +%s)
  secs=
  if [ -n "$BBX_TIME" ]; then
    secs=$(${quote(nodePath)} -e 'const t = Date.parse(process.env.BBX_TIME); if (!Number.isNaN(t)) console.log(Math.floor(t / 1000))' 2>/dev/null)
  else
    offset_ms=$(sed -n 's/.*"offsetMs": *\\([0-9]*\\).*/\\1/p' ${quote(offsetFile)} 2>/dev/null)
    if [ -n "$offset_ms" ]; then secs=$((now + offset_ms / 1000)); fi
  fi
  if [ -n "$secs" ]; then
    diff=$((secs - now))
    if [ "$diff" -ge 60 ] || [ "$diff" -le -60 ]; then
      at="$secs +0000"
      GIT_AUTHOR_DATE="$at" GIT_COMMITTER_DATE="$at" exec "$real_git" "$@"
    fi
  fi
fi
exec "$real_git" "$@"
`;
}

async function findExecutable(options: { name: string; searchPath: string; skipDir: string }): Promise<string | null> {
  for (const dir of options.searchPath.split(":")) {
    if (dir === "" || path.resolve(dir) === options.skipDir) continue;
    const candidate = path.join(dir, options.name);
    try {
      await fs.access(candidate, fsConstants.X_OK);
      return candidate;
    } catch (e) {
      const code = errnoCode(e);
      if (code !== "ENOENT" && code !== "EACCES" && code !== "ENOTDIR") throw e;
    }
  }
  return null;
}

/**
 * On a walk fixture, write the shim if missing or stale and return `searchPath`
 * with its directory first. Elsewhere, or with no real git on the path,
 * return `searchPath` unchanged.
 */
export async function pathWithGitShim(input: { boxRoot: string; searchPath: string | undefined }): Promise<string | undefined> {
  const { boxRoot, searchPath } = input;
  if (!isWalkFixture(boxRoot) || searchPath === undefined) return searchPath;
  const dir = path.resolve(boxShimDir(boxRoot));
  const realGit = await findExecutable({ name: "git", searchPath, skipDir: dir });
  if (realGit === null) return searchPath;
  const text = gitShimText({ realGit, nodePath: process.execPath, offsetFile: clockOffsetPath(boxRoot) });
  const file = path.join(dir, "git");
  const current = await fs.readFile(file, "utf-8").catch((e: unknown) => {
    if (errnoCode(e) === "ENOENT") return null;
    throw e;
  });
  if (current !== text) {
    await fs.mkdir(dir, { recursive: true });
    const tmp = `${file}.${process.pid}.tmp`;
    await fs.writeFile(tmp, text, { mode: 0o755 });
    await fs.chmod(tmp, 0o755);
    await fs.rename(tmp, file);
  }
  return searchPath.split(":").some((p) => path.resolve(p) === dir) ? searchPath : `${dir}:${searchPath}`;
}
