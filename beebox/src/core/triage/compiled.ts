/** Generated tie-breaks over the canonical guide and landmarks; never a place to edit rules. */
import { createHash } from "node:crypto";
import * as fs from "node:fs/promises";
import * as path from "node:path";
import { z } from "zod";
import { errnoCode } from "../../shared/error-guards.js";
import { parseRef, resolveRefPath } from "../../shared/ref-path/core.js";
import { isWithin } from "../../lib/box-containment.js";

export const COMPILED_INSTRUCTIONS_REF = "/_bookkeeping/triage/compiled-instructions.json";
const digest = (text: string): string => createHash("sha256").update(text).digest("hex");

// A length-2 array: the agent CLI rejects the `prefixItems` that z.tuple serializes to.
const pairSchema = z.array(z.string()).length(2);
const sourceDigestSchema = z.object({ ref: z.string(), digest: z.string().nullable() });
export const compileOutputSchema = z.object({
  destinations: z.array(z.object({
    ref: z.string(), role: z.enum(["work", "archive"]),
    /** Appended after the canonical rule, never replacing it. */
    boundaries: z.string(),
    facts: z.array(z.object({ text: z.string().min(1), ref: z.string() })),
  })),
  tieBreaks: z.array(z.object({ between: pairSchema, when: z.string().min(1), winner: z.string(), basis: z.string().min(1) })),
  conflicts: z.array(z.object({ between: pairSchema, when: z.string().min(1), why: z.string().min(1) })),
});
export type CompileOutput = z.infer<typeof compileOutputSchema>;
export const compiledInstructionsSchema = z.object({
  version: z.literal(1),
  note: z.literal("Generated by bbx triage compile. Edit the intake guide or a landmark instead; the next compile replaces this file."),
  /** Raw snapshot sources, then each cited card. */
  compiledFrom: z.array(sourceDigestSchema),
  principlesVersion: z.number().int().positive(),
  model: z.string().nullable(),
  destinations: compileOutputSchema.shape.destinations,
  tieBreaks: compileOutputSchema.shape.tieBreaks,
  conflicts: z.array(compileOutputSchema.shape.conflicts.element.extend({ questionRef: z.string() })),
});
export type CompiledInstructions = z.infer<typeof compiledInstructionsSchema>;
export type CompiledStatus = "current" | "stale" | "absent" | "invalid";
export type CompiledState =
  | { status: "current"; compiled: CompiledInstructions; digest: string }
  | { status: "stale" | "absent" }
  | { status: "invalid"; error: string };

/** A cited card's text; null when the ref is not a canonical box card ref, resolves outside the box, or is missing. */
export async function readCitedCard(boxRoot: string, ref: string): Promise<string | null> {
  const parsed = parseRef(ref);
  const relative = resolveRefPath({ fromPath: undefined, ref: parsed.path, kind: "card" });
  if (relative === null || ref !== `/${relative}` || parsed.query !== undefined || parsed.fragment !== undefined) return null;
  try {
    const real = await fs.realpath(path.join(boxRoot, relative));
    if (!isWithin(await fs.realpath(boxRoot), real)) return null;
    return await fs.readFile(real, "utf8");
  } catch (error) { if (errnoCode(error) === "ENOENT") return null; throw error; }
}

export const citedDigest = (text: string | null): string | null => text === null ? null : digest(text);

/** Current digest of each cited card, null when it is missing or not a box card. */
export async function citedDigests(boxRoot: string, refs: string[]): Promise<Array<{ ref: string; digest: string | null }>> {
  return Promise.all([...new Set(refs)].toSorted().map(async (ref) => ({ ref, digest: citedDigest(await readCitedCard(boxRoot, ref)) })));
}

/** The staleness key: raw sources, then the cited cards' current digests. */
export async function compileKey(boxRoot: string, options: { rawSources: Array<{ ref: string; digest: string | null }>; factRefs: string[] }): Promise<Array<{ ref: string; digest: string | null }>> {
  return [...options.rawSources.map(({ ref, digest: value }) => ({ ref, digest: value })), ...await citedDigests(boxRoot, options.factRefs)];
}

export async function loadCompiledInstructions(boxRoot: string, options: { rawSources: Array<{ ref: string; digest: string | null }>; principlesVersion: number }): Promise<CompiledState> {
  let text: string;
  try { text = await fs.readFile(path.join(boxRoot, COMPILED_INSTRUCTIONS_REF.slice(1)), "utf8"); }
  catch (error) { if (errnoCode(error) === "ENOENT") return { status: "absent" }; throw error; }
  let parsed: ReturnType<typeof compiledInstructionsSchema.safeParse>;
  try { parsed = compiledInstructionsSchema.safeParse(JSON.parse(text)); }
  catch (error) { return { status: "invalid", error: `${COMPILED_INSTRUCTIONS_REF}: ${String(error)}` }; }
  if (!parsed.success) return { status: "invalid", error: `${COMPILED_INSTRUCTIONS_REF}: ${parsed.error.issues.map((issue) => `${issue.path.join(".")}: ${issue.message}`).join("; ")}` };
  const compiled = parsed.data;
  const key = await compileKey(boxRoot, { rawSources: options.rawSources, factRefs: compiled.destinations.flatMap((d) => d.facts.map((fact) => fact.ref)) });
  if (compiled.principlesVersion !== options.principlesVersion || JSON.stringify(key) !== JSON.stringify(compiled.compiledFrom)) return { status: "stale" };
  return { status: "current", compiled, digest: digest(text) };
}

/** Canonical rule text first; role, compiled boundaries and cited facts follow it. */
export function compiledRules(canonical: string, entry: CompiledInstructions["destinations"][number]): string {
  const facts = entry.facts.map((fact) => `${fact.text} (from ${fact.ref})`);
  return [canonical, `Role: ${entry.role === "work" ? "work to be done" : "archive kept for reference"}.`, entry.boundaries.trim(), facts.length > 0 ? `Facts: ${facts.join("; ")}` : ""]
    .filter((line) => line !== "").join("\n");
}

export function compiledPolicy(compiled: CompiledInstructions, names: Map<string, string>): string {
  const name = (ref: string): string => names.get(ref) ?? ref;
  const lines: string[] = [];
  if (compiled.tieBreaks.length > 0) {
    lines.push("Tie-breaks compiled from these rules and the default principles:");
    for (const tie of compiled.tieBreaks) {
      const loser = tie.between.find((ref) => ref !== tie.winner) ?? tie.winner;
      lines.push(`- ${tie.when}: ${name(tie.winner)} over ${name(loser)} (basis: ${tie.basis}).`);
    }
  }
  if (compiled.conflicts.length > 0) {
    lines.push("Unresolved conflicts, awaiting the boxholder; use unclear for these cases:");
    for (const conflict of compiled.conflicts) lines.push(`- ${conflict.when}: ${conflict.between.map(name).join(" or ")}.`);
  }
  return lines.join("\n");
}
